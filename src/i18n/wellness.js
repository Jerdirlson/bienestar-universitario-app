/** fmt('Día {done} de {total}', { done: 2, total: 7 }) → 'Día 2 de 7' */
export function fmt(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

